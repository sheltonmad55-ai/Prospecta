import { test, expect } from '@playwright/test';
test('percurso completo: pesquisa, análise, mensagem persistente e CRM',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Explorar demonstração'}).click();
 await expect(page.getByRole('heading',{name:'O próximo cliente pode estar aqui.'})).toBeVisible();
 await page.getByRole('button',{name:'Pesquisar empresas',exact:true}).click();
 await expect(page.getByRole('heading',{name:/44 empresas encontradas/})).toBeVisible({timeout:30000});
 await page.getByRole('button',{name:'Ver empresa e possibilidades'}).first().click();
 await page.getByRole('button',{name:'Analisar oportunidade · 1 crédito'}).click();
 await expect(page.getByRole('heading',{name:'Criação de websites',exact:true})).toBeVisible({timeout:30000});
 await page.getByRole('button',{name:'Guardar oportunidade',exact:true}).click();
 await page.getByRole('button',{name:'Preparar a conversa'}).click();
 await page.getByLabel('Mensagem de abordagem').fill('Bom dia! Podemos conversar sobre o vosso negócio?');
 await page.getByRole('button',{name:'Guardar edição'}).click();
 await expect(page.getByRole('status')).toContainText('Mensagem guardada.');
 await page.reload();
 await expect(page.getByLabel('Mensagem de abordagem')).toHaveValue('Bom dia! Podemos conversar sobre o vosso negócio?');
 await page.getByRole('button',{name:'Minhas oportunidades',exact:true}).click();
 await page.locator('.lead-row').first().click();
 await page.locator('select[name="stage"]').selectOption('Proposta');
 await page.getByLabel('Valor proposto (MT)').fill('15000');
 await page.getByRole('button',{name:'Guardar alterações'}).click();
 await expect(page.getByRole('status')).toContainText('Oportunidade actualizada.');
 await page.getByRole('button',{name:'Fechar oportunidade'}).click();
 await page.getByRole('button',{name:'Visão geral',exact:true}).click();
 await expect(page.locator('.stat-card').last()).toContainText('15');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
});
