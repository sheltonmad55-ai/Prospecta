import { chromium } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
const browser=await chromium.connectOverCDP('http://127.0.0.1:9222');
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const page=await context.newPage();const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const directory=process.env.SCREENSHOT_DIR||'test-results/screenshots';mkdirSync(directory,{recursive:true});
await page.goto('http://127.0.0.1:4317',{waitUntil:'networkidle'});
await page.screenshot({path:directory+'/01-inicio.png',fullPage:true});
await page.getByRole('button',{name:'Explorar demonstração'}).click();
await page.getByRole('heading',{name:'O próximo cliente pode estar aqui.'}).waitFor();
await page.getByRole('button',{name:'Pesquisar empresas',exact:true}).click();
await page.getByRole('heading',{name:/44 empresas encontradas/}).waitFor({timeout:30000});
await page.screenshot({path:directory+'/02-pesquisa.png',fullPage:true});
await page.getByRole('button',{name:'Ver empresa e possibilidades'}).first().click();
await page.getByRole('heading',{name:'Primeiro, os factos.'}).waitFor();
await page.getByRole('button',{name:'Analisar oportunidade · 1 crédito'}).click();
await page.getByRole('heading',{name:'Criação de websites',exact:true}).waitFor({timeout:30000});
await page.getByRole('button',{name:'Guardar oportunidade',exact:true}).click();
await page.getByRole('button',{name:'Preparar a conversa'}).click();
await page.getByLabel('Mensagem de abordagem').fill('Bom dia! Gostaria de perceber se o nosso serviço pode ser útil para o vosso negócio.');
await page.getByRole('button',{name:'Guardar edição'}).click();
await page.getByRole('status').filter({hasText:'Mensagem guardada.'}).waitFor();
await page.screenshot({path:directory+'/03-abordagem.png',fullPage:true});
await page.reload({waitUntil:'networkidle'});
await page.getByLabel('Mensagem de abordagem').waitFor();
if(!await page.getByLabel('Mensagem de abordagem').inputValue().then(v=>v.startsWith('Bom dia! Gostaria')))throw new Error('Draft persistence failed');
await page.getByRole('button',{name:'Minhas oportunidades',exact:true}).click();
await page.locator('.lead-row').first().click();
await page.getByLabel('Etapa',{exact:true}).selectOption('Proposta');
await page.getByLabel('Próximo passo').fill('Apresentar uma demonstração');
await page.getByLabel('Valor proposto (MT)').fill('15000');
await page.getByRole('button',{name:'Guardar alterações'}).click();
await page.getByRole('status').filter({hasText:'Oportunidade actualizada.'}).waitFor();
await page.getByRole('button',{name:'Fechar oportunidade'}).click();
await page.getByRole('button',{name:'Visão geral',exact:true}).click();
await page.getByText('15 000 MT',{exact:true}).waitFor().catch(()=>{});
await page.screenshot({path:directory+'/04-painel.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:directory+'/05-mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
if(overflow)throw new Error('Mobile horizontal overflow');
if(errors.length)throw new Error(errors.join('\n'));
writeFileSync(directory+'/validation.json',JSON.stringify({journey:'demo-search-analysis-draft-crm-dashboard',passed:true,consoleErrors:errors,mobileOverflow:overflow},null,2));
console.log('Browser journey passed; screenshots saved to '+directory);
await context.close();await browser.close();
